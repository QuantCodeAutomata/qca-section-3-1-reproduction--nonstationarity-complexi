"""
Reproduces recession-specific OOS R² table.

Uses the same per-seed daily predictions cached by run_exp2.  Computes OOS R²
separately for the full OOS window and three NBER recession sub-windows.

Ambiguity resolutions:
  - Recession windows follow the exact definitions in get_recession_masks()
    (gulf_war, dot_com, gfc) which match the paper's Table 2 dates exactly.
  - R² is computed using compute_oos_r2 on the date-filtered subset per recession.
  - AMBIGUITY: the paper contains a note about daily vs monthly data in a table;
    the implementation uses daily observations grouped into monthly periods,
    which is the dominant methodology throughout.
"""

import sys
import os

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import numpy as np
import pandas as pd

from src.data_loader import get_recession_masks
from src.evaluation import compute_oos_r2
from exp.exp2_atoms_vs_baselines import run_exp2


def run_exp3(
    X: pd.DataFrame,
    y: pd.DataFrame,
    output_dir: str = 'results',
    fast_mode: bool = True,
) -> pd.DataFrame:
    """
    Compute method-level OOS R² for the full sample and three recession windows.

    Reuses per-seed predictions generated by run_exp2 (or loads them from the
    cached CSV produced by a previous run).

    Parameters
    ----------
    X : pd.DataFrame
        Daily feature panel (DatetimeIndex).
    y : pd.DataFrame
        Daily return panel (DatetimeIndex); columns are industry names.
    output_dir : str
        Directory for output CSV and for the cached prediction file.
    fast_mode : bool
        Passed through to run_exp2 when predictions must be generated.

    Returns
    -------
    pd.DataFrame
        Rows indexed by method; columns are Full OOS, Gulf War, 2001 Recession,
        GFC.  Values are R² averaged across industries and seeds.

    Notes
    -----
    Expected approximate values (full mode, all 17 industries):
        Full OOS:  ATOMS 0.049, Fixed-val(32) 0.022, Fixed-val(512) 0.043, Fixed-CV 0.035
        Gulf War:  ATOMS 0.027, Fixed-val(32) 0.009, Fixed-val(512) -0.031, Fixed-CV -0.007
        2001:      ATOMS 0.125, Fixed-val(32) 0.096, Fixed-val(512) 0.117, Fixed-CV 0.071
        GFC:       ATOMS 0.041, Fixed-val(32) -0.001, Fixed-val(512) 0.039, Fixed-CV 0.014
    """
    os.makedirs(output_dir, exist_ok=True)

    # Load or generate per-seed predictions from exp2
    pred_cache = os.path.join(output_dir, 'exp2_predictions.csv')
    if os.path.exists(pred_cache):
        print(f'  Loading cached predictions from {pred_cache}')
        preds_df = pd.read_csv(pred_cache, parse_dates=['date'])
    else:
        print('  No cached predictions found; running exp2...')
        results2 = run_exp2(X, y, output_dir=output_dir, fast_mode=fast_mode)
        preds_df = results2['predictions']

    methods = ['ATOMS', 'Fixed-val(32)', 'Fixed-val(128)', 'Fixed-val(512)', 'Fixed-CV']
    present_methods = [m for m in methods if m in preds_df['method'].unique()]
    industries = preds_df['industry'].unique().tolist()
    n_seeds = preds_df['seed'].nunique()

    # Build recession boolean masks over the full prediction date range
    all_dates = pd.DatetimeIndex(preds_df['date'].unique())
    rec_masks_global = get_recession_masks(all_dates)
    # rec_masks_global: {key: pd.Series(bool, index=all_dates)}

    # Map display names → mask keys
    period_map = {
        'Full OOS': 'full_oos',
        'Gulf War': 'gulf_war',
        '2001 Recession': 'dot_com',
        'GFC': 'gfc',
    }
    col_order = list(period_map.keys())

    # Helper: compute average R² across seeds for a given date filter
    def _avg_r2_for_period(method: str, ind: str, date_filter: pd.Series) -> float:
        """Average OOS R² over seeds, filtering dates using a boolean Series."""
        seed_r2 = []
        for seed in range(n_seeds):
            row_mask = (
                (preds_df['seed'] == seed)
                & (preds_df['method'] == method)
                & (preds_df['industry'] == ind)
            )
            sub = preds_df.loc[row_mask].sort_values('date')
            if sub.empty:
                continue
            # Align recession mask to this sub-series' dates
            sub_dates = pd.DatetimeIndex(sub['date'])
            period_in_sub = date_filter.reindex(sub_dates, fill_value=False).values
            if period_in_sub.sum() == 0:
                continue
            y_true_filt = sub['y_true'].values[period_in_sub]
            y_pred_filt = sub['y_pred'].values[period_in_sub]
            if len(y_true_filt) < 2:
                continue
            seed_r2.append(compute_oos_r2(y_true_filt, y_pred_filt))
        return float(np.nanmean(seed_r2)) if seed_r2 else np.nan

    summary_records = []
    for method in present_methods:
        row = {'Method': method}
        for display_name, mask_key in period_map.items():
            date_filter = rec_masks_global[mask_key]
            ind_r2 = [_avg_r2_for_period(method, ind, date_filter) for ind in industries]
            ind_r2_valid = [v for v in ind_r2 if not np.isnan(v)]
            row[display_name] = float(np.nanmean(ind_r2_valid)) if ind_r2_valid else np.nan
        summary_records.append(row)

    summary_df = pd.DataFrame(summary_records).set_index('Method')
    summary_df = summary_df[col_order]

    out_path = os.path.join(output_dir, 'exp3_recession_table.csv')
    summary_df.to_csv(out_path)
    print(f'  Saved recession table to {out_path}')

    print('\nExp3 — Recession-period OOS R² (averaged across industries)')
    print(summary_df.round(4).to_string())

    return summary_df


if __name__ == '__main__':
    from src.data_loader import load_full_panel
    X, y = load_full_panel()
    result = run_exp3(X, y, fast_mode=True)
    print('\nExp3 — Recession-period OOS R²')
    print(result.to_string())
